PFSENSE = """<?xml version="1.0"?>
<pfsense>
  <interfaces>
    <lan><if>em1</if><descr>CORP</descr><ipaddr>10.40.0.1</ipaddr><subnet>24</subnet></lan>
    <opt1><if>em2</if><descr>CDE</descr><ipaddr>10.30.0.1</ipaddr><subnet>24</subnet></opt1>
  </interfaces>
  <aliases><alias><name>CARD_DB</name><type>host</type><address>10.30.0.20</address></alias>
           <alias><name>DB_PORTS</name><type>port</type><address>5432 3306</address></alias></aliases>
  <filter>
    <rule><tracker>100</tracker><type>pass</type><interface>lan</interface><protocol>tcp</protocol>
      <source><network>lan</network></source><destination><address>CARD_DB</address><port>DB_PORTS</port></destination>
      <descr>Legacy reporting</descr></rule>
    <rule><tracker>101</tracker><type>block</type><interface>lan</interface><protocol>tcp</protocol>
      <source><network>lan</network></source><destination><network>opt1</network></destination><descr>Block CORP to CDE</descr></rule>
    <rule><tracker>102</tracker><type>pass</type><interface>lan</interface><disabled/>
      <source><any/></source><destination><any/></destination><descr>Disabled allow-all</descr></rule>
  </filter>
</pfsense>"""


def test_iptables_export_names_the_rule_in_first_match_order():
    ruleset = parse_export(IPTABLES)
    assert ruleset["kind"] == "iptables"
    hit = first_match(ruleset, "10.40.0.100", "10.30.0.20", "tcp", 5432)
    assert hit["label"] == "legacy-reporting" and hit["action"] == "pass"
    blocked = first_match(ruleset, "10.40.0.100", "10.30.0.20", "tcp", 3306)
    assert blocked["action"] == "block"


def test_pfsense_export_resolves_interfaces_aliases_and_skips_disabled_rules():
    ruleset = parse_export(PFSENSE)
    hit = first_match(ruleset, "10.40.0.100", "10.30.0.20", "tcp", 5432)
    assert (hit["label"], hit["tracker"], hit["action"]) == ("Legacy reporting", "100", "pass")
    blocked = first_match(ruleset, "10.40.0.100", "10.30.0.10", "tcp", 22)
    assert blocked["label"] == "Block CORP to CDE" and blocked["action"] == "block"
    default = first_match(ruleset, "10.40.0.100", "10.99.0.1", "udp", 53)
    assert default["action"] == "block" and "default deny" in default["label"]
    assert log_rule_label({"format": "pf_filterlog", "rule": "100"}, ruleset) == "Legacy reporting (tracker 100)"


@pytest.mark.parametrize("text,message", [("", "empty"), ("hello world", "Not a rule export"),
                                          ('<?xml version="1.0"?><!DOCTYPE x [<!ENTITY a "b">]><pfsense/>', "DOCTYPE"),
                                          ("<pfsense><filter></filter></pfsense>", "no enabled firewall rules")])
def test_bad_rule_exports_are_explained(text, message):
    with pytest.raises(RuleExportError, match=message):
        parse_export(text)


def test_log_prefix_becomes_a_readable_rule_name():
    assert log_rule_label({"format": "iptables", "rule": "Nov 21 10:00:00 fw ulogd[1]: SEGCHECK-ACCEPT legacy-reporting"}) == "legacy-reporting"


def _report(rows, networks, evidence=None):
    """A minimal saved report: rows of (check_id, host, zone, port, expected, observed, result, mappings)."""
    results, details, attempts = [], [], []
    for check_id, host, zone, port, expected, observed, result, mappings in rows:
        results.append({"check_id": check_id, "check_name": check_id, "source_zone": "corp", "destination_zone": zone,
                        "destination_host": host, "protocol": "tcp", "ports": [port], "expected": expected, "observed": observed,
                        "result": result, "framework_mappings": mappings, "pci_requirements": []})
        details.append({"check_id": check_id, "destination_host": host, "port": port, "protocol": "tcp", "observed": observed,
                        "reason": "tcp_connected" if observed == "reachable" else "tcp_timeout", "source_zone": "corp",
                        "destination_zone": zone})
        attempts.append({"check_id": check_id, "host": host, "port": port, "protocol": "tcp", "observed": observed,
                         "evidence": (evidence or {}).get(check_id, "not_connected")})
    return {"results": results, "probe_measurement": {"details": details},
            "boundary_evidence": {"attempts": attempts, "devices": [{"connected": bool(evidence)}]},
            "assessment": {"source_zone": "corp", "environment": {"networks": networks, "source_zone": "corp"}}}


NETWORKS = {"corp": {"role": "corporate"}, "cde": {"role": "cde"}, "hr": {"role": "hr"}}
PCI = [{"framework": "pci_dss", "control_id": "1.3.1"}]
ISO = [{"framework": "iso27002", "control_id": "8.22"}]


def test_assistant_gives_each_standard_its_own_verdict():
    """HR database reachable (ISO 8.22 fails) while the CDE holds (PCI 1.3.1 met): the standards disagree."""
    report = _report([("A", "10.30.0.20", "cde", 5432, "deny", "inconclusive", "INCONCLUSIVE", PCI + ISO),
                      ("B", "10.50.0.10", "hr", 5432, "deny", "reachable", "FAIL", ISO)], NETWORKS)
    result = compliance_assistant.assess(report_view.build(report), report["results"])
    verdicts = {s["framework"]: s["verdict"] for s in result["standards"]}
    assert verdicts == {"iso27002": "not_met", "pci_dss": "met_unproven"}
    assert "disagree" in result["conclusion"]
    iso = next(s for s in result["standards"] if s["framework"] == "iso27002")
    control = next(c for c in iso["controls"] if c["id"] == "8.22")
    assert control["failing"] == ["10.50.0.10 TCP 5432"] and control["fix"] and control["alternative"]
    assert any("Databases should only accept" in text for text in control["playbooks"])


def test_own_rules_are_checked_against_every_standard_by_retrieval():
    report = _report([("A", "10.30.0.20", "cde", 5432, "deny", "reachable", "FAIL", [])], NETWORKS)
    result = compliance_assistant.assess(report_view.build(report), report["results"])
    assert {s["framework"] for s in result["standards"]} == {"pci_dss", "nist_sp800_53", "iso27002", "cis_controls"}
    pci = next(s for s in result["standards"] if s["framework"] == "pci_dss")
    assert pci["verdict"] == "not_met" and any(c["id"] == "1.3.1" and c["verdict"] == "not_met" for c in pci["controls"])
    assert result["notes"][0]["top"], "retrieval explains which passages it used"


def test_compare_finds_fixed_paths_and_regressions():
    before = _report([("A", "10.30.0.20", "cde", 5432, "deny", "reachable", "FAIL", []),
                      ("B", "10.50.0.10", "hr", 445, "deny", "inconclusive", "INCONCLUSIVE", [])], NETWORKS)
    after = _report([("A", "10.30.0.20", "cde", 5432, "deny", "inconclusive", "INCONCLUSIVE", []),
                     ("B", "10.50.0.10", "hr", 445, "deny", "reachable", "FAIL", [])], NETWORKS)
    diff = report_view.compare(before, after)
    assert diff["counts"]["fixed"] == 1 and diff["counts"]["regression"] == 1
    assert diff["headline"]["word"] == "REGRESSION"
    assert report_view.compare(before, before)["headline"]["word"] == "STILL FAILING"


def test_drop_log_without_a_rule_name_reads_as_the_final_drop_rule():
    assert log_rule_label({"format": "iptables", "rule": "Nov 21 21:45:12 ulogd[1]: SEGCHECK-DROP"}) == "final drop-and-log rule (SEGCHECK-DROP)"
